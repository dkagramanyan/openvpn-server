# Columns added to vpn_sessions after 1.4: an existing database gets them on start.
_SESSION_COLUMNS = (("proto", "TEXT"), ("platform", "TEXT"), ("client_ver", "TEXT"), ("end_reason", "TEXT"),
                    ("grp", "BIGINT"))

_HISTORY = (("vpn_sessions", "connected_at"), ("relay_sessions", "started_at"), ("relay_flows", "ts"),
            ("traffic_minute", "ts"), ("traffic_hour", "ts"), ("traffic_day", "ts"),
            ("section_traffic", "ts"), ("section_domains", "ts"), ("section_pending", "ts"))
_TRAFFIC_TABLES = ("traffic_minute", "traffic_hour", "traffic_day")
SOURCES = ("vpn", "relay")

MINUTE_RETENTION = 2 * 86400      # minute buckets are kept for two days
HOUR_RETENTION = 90 * 86400       # hourly buckets for 90 days, daily forever
EVENT_RETENTION = 365 * 86400     # the audit log
RELAY_FLOW_RETENTION = 7 * 86400  # relay connections with their destinations
SECTION_DOMAIN_RETENTION = 7 * 86400   # per-domain detail of the traffic by section
# A phone drops the tunnel whenever it sleeps and reconnects on wake, hundreds of times a day.
# Sessions of one client from one address that follow each other within this gap are one visit.
MERGE_GAP = 15 * 60
SHORT_SESSION = 60                # "short" in the connection statistics: under a minute

_TRAFFIC_UNION = """
    SELECT ts, client_name, source, bytes_in, bytes_out FROM traffic_minute WHERE ts >= ? AND ts < ?
    UNION ALL
    SELECT ts, client_name, source, bytes_in, bytes_out FROM traffic_hour   WHERE ts >= ? AND ts < ?
    UNION ALL
    SELECT ts, client_name, source, bytes_in, bytes_out FROM traffic_day    WHERE ts >= ? AND ts < ?
"""


def empty_point(ts: int) -> dict[str, int]:
    return {"ts": ts, "bytes_in": 0, "bytes_out": 0, "vpn_in": 0, "vpn_out": 0, "relay_in": 0, "relay_out": 0}


def split_address(address: str | None) -> tuple[str | None, str]:
    """("udp" | "tcp" | None, "ip:port") of a real address as OpenVPN prints it:
    "udp4:203.0.113.5:1194", "tcp4-server:203.0.113.5:40112", or just "203.0.113.5:1194" before 2.7."""
    address = address or ""
    head, sep, rest = address.partition(":")
    if sep and head[:3] in ("udp", "tcp"):
        return head[:3], rest
    return None, address


def real_ip(address: str | None) -> str:
    return split_address(address)[1].rpartition(":")[0]


def connection_parameters(dsn=""):
    if dsn:
        return psycopg.conninfo.conninfo_to_dict(dsn)
    password = os.environ.get("PGPASSWORD", os.environ.get("OPENVPN_DB_PASSWORD", ""))
    if not password:
        raise ValueError("Run bin/setup-env.py to configure PostgreSQL credentials")
    return {"host": os.environ.get("PGHOST", "127.0.0.1"),
            "port": os.environ.get("PGPORT", os.environ.get("OPENVPN_DB_PORT", "5433")),
            "dbname": os.environ.get("PGDATABASE", "openvpn"), "user": os.environ.get("PGUSER", "openvpn"),
            "password": password}


class Connection:
    """Keep the app's bound-parameter interface while using native PostgreSQL."""
    def __init__(self, raw):
        self.raw = raw

    def execute(self, statement, params=()):
        if params:
            statement = statement.replace("%", "%%").replace("?", "%s")
            return self.raw.execute(statement, params)
        return self.raw.execute(statement)

    @property
    def in_transaction(self):
        return self.raw.info.transaction_status != psycopg.pq.TransactionStatus.IDLE

    def close(self):
        self.raw.close()


class Database:
    def __init__(self, dsn: str = "", *, schema: str = "public") -> None:
        if not isinstance(dsn, str):
            raise ValueError("Database requires PostgreSQL connection settings, not a file path")
        self.dsn, self.schema = dsn, schema
        self._local = threading.local()
        self._write_lock = threading.RLock()
        conn = self._conn()
        with conn.raw.transaction():
            conn.raw.execute("SELECT pg_advisory_xact_lock(hashtext(%s))", ("openvpn-schema:" + schema,))
            for statement in SCHEMA.split(";"):
                if statement.strip(): conn.execute(statement)
            for column, kind in _SESSION_COLUMNS:
                conn.execute(f"ALTER TABLE vpn_sessions ADD COLUMN IF NOT EXISTS {column} {kind}")
            for column in ("client_name", "client_serial"):
                conn.execute(f"ALTER TABLE users ADD COLUMN IF NOT EXISTS {column} TEXT")
            for table in _TRAFFIC_TABLES:
                self._traffic_source(conn, table)
            # 2.4: the numeric destination a relay flow dialled, and whether its bytes were
            # counted by section. Rows saved before have no address: they count as done.
            conn.execute("ALTER TABLE relay_flows ADD COLUMN IF NOT EXISTS address TEXT")
            # 2.6: a one-time link carries the OpenVPN profile or the Apple relay profile.
            conn.execute("ALTER TABLE share_tokens ADD COLUMN IF NOT EXISTS kind TEXT NOT NULL DEFAULT 'openvpn'")
            # 2.12.1: what a spent link handed out, kept for a few minutes: phones fetch a profile twice.
            conn.execute("ALTER TABLE share_tokens ADD COLUMN IF NOT EXISTS content BYTEA")
            conn.execute("ALTER TABLE share_tokens ADD COLUMN IF NOT EXISTS served_until BIGINT")
            # 2.7: the client's Telegram username (lower case, no "@"), and the account that claimed it.
            for column, kind in (("telegram", "TEXT"), ("telegram_id", "BIGINT"), ("telegram_name", "TEXT")):
                conn.execute(f"ALTER TABLE clients ADD COLUMN IF NOT EXISTS {column} {kind}")
            # 2.11: the client's own number of configs (relay devices + Xray keys); NULL = the default.
            conn.execute("ALTER TABLE clients ADD COLUMN IF NOT EXISTS config_limit INTEGER")
            conn.execute("CREATE UNIQUE INDEX IF NOT EXISTS clients_telegram ON clients(telegram) WHERE telegram IS NOT NULL")
            conn.execute("CREATE UNIQUE INDEX IF NOT EXISTS clients_telegram_id ON clients(telegram_id) WHERE telegram_id IS NOT NULL")
            if not conn.execute("SELECT 1 FROM information_schema.columns WHERE table_schema = ? AND "
                                "table_name = 'relay_flows' AND column_name = 'sectioned'", (schema,)).fetchone():
                conn.execute("ALTER TABLE relay_flows ADD COLUMN sectioned BOOLEAN NOT NULL DEFAULT true")
                conn.execute("ALTER TABLE relay_flows ALTER COLUMN sectioned SET DEFAULT false")
            conn.execute("CREATE INDEX IF NOT EXISTS relay_flows_unsectioned ON relay_flows (ts) WHERE NOT sectioned")
            conn.execute("CREATE INDEX IF NOT EXISTS vpn_sessions_grp ON vpn_sessions (grp)")
            conn.execute("CREATE UNIQUE INDEX IF NOT EXISTS users_client ON users(client_name) WHERE client_name IS NOT NULL")
            conn.execute("CREATE OR REPLACE VIEW relay_policy_settings AS SELECT key, value FROM settings "
                         "WHERE key = 'apple_relay' OR starts_with(key, 'relay_client:')")
            # What the policy service needs of a bound device: never its code, key or certificate.
            conn.execute("CREATE OR REPLACE VIEW relay_policy_devices AS SELECT id, client_name, fingerprint, revoked_at "
                         "FROM relay_devices WHERE enrolled_at IS NOT NULL")
            if conn.execute("SELECT 1 FROM pg_roles WHERE rolname = 'relay_policy'").fetchone():
                if schema != "public":
                    conn.raw.execute(pgsql.SQL("GRANT USAGE ON SCHEMA {} TO relay_policy").format(pgsql.Identifier(schema)))
                conn.execute("GRANT SELECT ON relay_policy_settings TO relay_policy")
                conn.execute("GRANT SELECT ON relay_policy_devices TO relay_policy")

    def _traffic_source(self, conn: Connection, table: str) -> None:
        """Traffic tables written before 2.3 have no source column and a (ts, client_name) key."""
        conn.execute(f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS source TEXT NOT NULL DEFAULT 'vpn'")
        key = conn.raw.execute(
            """SELECT c.conname, ARRAY(SELECT a.attname::text FROM unnest(c.conkey) k
                                       JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = k) AS cols
               FROM pg_constraint c JOIN pg_class t ON t.oid = c.conrelid JOIN pg_namespace n ON n.oid = t.relnamespace
               WHERE c.contype = 'p' AND t.relname = %s AND n.nspname = %s""", (table, self.schema)).fetchone()
        if key and "source" in key["cols"]:
            return
        if key:
            conn.raw.execute(pgsql.SQL("ALTER TABLE {} DROP CONSTRAINT {}").format(
                pgsql.Identifier(table), pgsql.Identifier(key["conname"])))
        conn.execute(f"ALTER TABLE {table} ADD PRIMARY KEY (ts, client_name, source)")

    def _conn(self) -> Connection:
        conn = getattr(self._local, "conn", None)
        if conn is None or conn.raw.closed or conn.raw.broken:
            raw = psycopg.connect(**{"connect_timeout": 5, **connection_parameters(self.dsn)}, autocommit=True, row_factory=dict_row)
            if not raw.execute("SELECT 1 FROM pg_namespace WHERE nspname=%s", (self.schema,)).fetchone():
                raw.execute(pgsql.SQL("CREATE SCHEMA {}").format(pgsql.Identifier(self.schema)))
            raw.execute(pgsql.SQL("SET search_path TO {}").format(pgsql.Identifier(self.schema)))
            conn = Connection(raw)
            self._local.conn = conn
        return conn

    @contextmanager
    def tx(self) -> Iterator[Connection]:
        with self._write_lock:
            conn = self._conn()
            try:
                with conn.raw.transaction():
                    yield conn
            except BaseException:
                if conn.raw.closed or conn.raw.broken: self._local.conn = None
                raise

    def execute(self, sql: str, params: tuple | list = ()):
        with self.tx() as conn:
            return conn.execute(sql, params)

    def query(self, sql: str, params: tuple | list = ()) -> list[dict[str, Any]]:
        return self._conn().execute(sql, params).fetchall()

    def one(self, sql: str, params: tuple | list = ()) -> dict[str, Any] | None:
        return self._conn().execute(sql, params).fetchone()

    # -- settings ------------------------------------------------------------
    def get_setting(self, key: str, default: str | None = None) -> str | None:
        row = self.one("SELECT value FROM settings WHERE key = ?", (key,))
        return row["value"] if row else default

    def set_setting(self, key: str, value: str) -> None:
        self.execute(
            "INSERT INTO settings (key, value) VALUES (?, ?) ON CONFLICT(key) DO UPDATE SET value = excluded.value",
            (key, value),
        )

    # -- events --------------------------------------------------------------
    def add_event(self, kind: str, client_name: str | None = None, actor: str | None = None,
                  detail: str | None = None, conn: Connection | None = None) -> None:
        sql = "INSERT INTO events (ts, kind, client_name, actor, detail) VALUES (?, ?, ?, ?, ?)"
        params = (int(time.time()), kind, client_name, actor, detail)
        if conn is not None:
            conn.execute(sql, params)
        else:
            self.execute(sql, params)

    # -- traffic -------------------------------------------------------------
    @staticmethod
    def add_traffic(conn: Connection, ts_minute: int, client_name: str, d_in: int, d_out: int,
                    source: str = "vpn") -> None:
        """bytes_in is what the client sent (upload), bytes_out what it received (download)."""
        if d_in <= 0 and d_out <= 0:
            return
        conn.execute(
            """INSERT INTO traffic_minute (ts, client_name, source, bytes_in, bytes_out) VALUES (?, ?, ?, ?, ?)
               ON CONFLICT(ts, client_name, source) DO UPDATE SET
                   bytes_in = traffic_minute.bytes_in + excluded.bytes_in,
                   bytes_out = traffic_minute.bytes_out + excluded.bytes_out""",
            (ts_minute, client_name, source, max(d_in, 0), max(d_out, 0)),
        )

    def traffic_by_client(self, start: int, end: int) -> dict[str, dict[str, tuple[int, int]]]:
        """{client: {"vpn": (in, out), "relay": (in, out)}} for [start, end)."""
        rows = self.query(
            f"SELECT client_name, source, SUM(bytes_in) AS bi, SUM(bytes_out) AS bo FROM ({_TRAFFIC_UNION}) "
            "GROUP BY client_name, source", (start, end) * 3)
        out: dict[str, dict[str, tuple[int, int]]] = {}
        for r in rows:
            out.setdefault(r["client_name"], {})[r["source"]] = (int(r["bi"] or 0), int(r["bo"] or 0))
        return out

    def totals_by_client(self, start: int, end: int) -> dict[str, tuple[int, int]]:
        return {name: (sum(v[0] for v in by.values()), sum(v[1] for v in by.values()))
                for name, by in self.traffic_by_client(start, end).items()}

    def totals(self, start: int, end: int, client_name: str | None = None,
               source: str | None = None) -> tuple[int, int]:
        where, params = [], list((start, end) * 3)
        for column, value in (("client_name", client_name), ("source", source)):
            if value:
                where.append(f"{column} = ?")
                params.append(value)
        row = self.one(
            f"SELECT SUM(bytes_in) AS bi, SUM(bytes_out) AS bo FROM ({_TRAFFIC_UNION})"
            + (" WHERE " + " AND ".join(where) if where else ""), params)
        return (int(row["bi"] or 0), int(row["bo"] or 0)) if row else (0, 0)

    def series(self, start: int, end: int, bucket: int, client_name: str | None = None,
               tz_offset: int = 0) -> list[dict[str, int]]:
        """Traffic per bucket: the total and its OpenVPN and relay parts. tz_offset (seconds east of
        UTC) aligns day buckets to local midnight."""
        where = " WHERE client_name = ?" if client_name else ""
        params: list[Any] = list((start, end) * 3)
        if client_name:
            params.append(client_name)
        rows = self.query(
            f"""SELECT ((ts + ?) / ?) * ? - ? AS b, source, SUM(bytes_in) AS bi, SUM(bytes_out) AS bo
                FROM ({_TRAFFIC_UNION}){where} GROUP BY b, source ORDER BY b""",
            [tz_offset, bucket, bucket, tz_offset] + params,
        )
        points: dict[int, dict[str, int]] = {}
        for r in rows:
            p = points.setdefault(int(r["b"]), empty_point(int(r["b"])))
            source = r["source"] if r["source"] in SOURCES else "vpn"
            for key, value in (("in", int(r["bi"] or 0)), ("out", int(r["bo"] or 0))):
                p[f"{source}_{key}"] += value
                p[f"bytes_{key}"] += value
        return list(points.values())

    def first_traffic_ts(self) -> int | None:
        row = self.one(
            "SELECT MIN(ts) AS t FROM (SELECT MIN(ts) AS ts FROM traffic_minute UNION ALL "
            "SELECT MIN(ts) FROM traffic_hour UNION ALL SELECT MIN(ts) FROM traffic_day)"
        )
        return int(row["t"]) if row and row["t"] is not None else None

    def rollup(self, now: int | None = None) -> None:
        """Fold old minute buckets into hourly ones and old hourly buckets into daily ones."""
        now = now or int(time.time())
        with self.tx() as conn:
            cutoff = now - MINUTE_RETENTION
            conn.execute(
                """INSERT INTO traffic_hour (ts, client_name, source, bytes_in, bytes_out)
                   SELECT (ts / 3600) * 3600, client_name, source, SUM(bytes_in), SUM(bytes_out)
                   FROM traffic_minute WHERE ts < ? GROUP BY 1, 2, 3
                   ON CONFLICT(ts, client_name, source) DO UPDATE SET
                       bytes_in = traffic_hour.bytes_in + excluded.bytes_in,
                       bytes_out = traffic_hour.bytes_out + excluded.bytes_out""",
                (cutoff,),
            )
            conn.execute("DELETE FROM traffic_minute WHERE ts < ?", (cutoff,))
            cutoff = now - HOUR_RETENTION
            conn.execute(
                """INSERT INTO traffic_day (ts, client_name, source, bytes_in, bytes_out)
                   SELECT (ts / 86400) * 86400, client_name, source, SUM(bytes_in), SUM(bytes_out)
                   FROM traffic_hour WHERE ts < ? GROUP BY 1, 2, 3
                   ON CONFLICT(ts, client_name, source) DO UPDATE SET
                       bytes_in = traffic_day.bytes_in + excluded.bytes_in,
                       bytes_out = traffic_day.bytes_out + excluded.bytes_out""",
                (cutoff,),
            )
            conn.execute("DELETE FROM traffic_hour WHERE ts < ?", (cutoff,))
            conn.execute("DELETE FROM web_sessions WHERE expires_at < ?", (now,))
            conn.execute("DELETE FROM rejections WHERE day < ?", (now - HOUR_RETENTION,))
            conn.execute("DELETE FROM share_tokens WHERE expires_at < ? AND (served_until IS NULL OR served_until < ?)", (now, now))
            conn.execute("UPDATE share_tokens SET content = NULL WHERE content IS NOT NULL AND served_until < ?", (now,))
            conn.execute("DELETE FROM events WHERE ts < ?", (now - EVENT_RETENTION,))
            conn.execute("DELETE FROM relay_flows WHERE ts < ?", (now - RELAY_FLOW_RETENTION,))
            conn.execute("DELETE FROM section_domains WHERE ts < ?", (now - SECTION_DOMAIN_RETENTION,))
            # Hours older than HOUR_RETENTION become their UTC day, kept forever.
            cutoff = now - HOUR_RETENTION
            conn.execute(
                """INSERT INTO section_traffic (ts, client_name, source, section, bytes_in, bytes_out, flows)
                   SELECT (ts / 86400) * 86400, client_name, source, section, SUM(bytes_in), SUM(bytes_out), SUM(flows)
                   FROM section_traffic WHERE ts < ? AND ts % 86400 <> 0 GROUP BY 1, 2, 3, 4
                   ON CONFLICT (ts, client_name, source, section) DO UPDATE SET
                       bytes_in = section_traffic.bytes_in + excluded.bytes_in,
                       bytes_out = section_traffic.bytes_out + excluded.bytes_out,
                       flows = section_traffic.flows + excluded.flows""", (cutoff,))
            conn.execute("DELETE FROM section_traffic WHERE ts < ? AND ts % 86400 <> 0", (cutoff,))

    # -- client history ------------------------------------------------------
    def archive_client_history(self, name: str, before: int | None = None) -> str | None:
        """Move the sessions and traffic of <name> (those older than <before>, if given) to an
        archive key, so a new certificate with the same name starts with a clean history."""
        cond = " AND {col} < ?" if before is not None else ""
        extra = [before] if before is not None else []
        with self.tx() as conn:
            if not any(conn.execute(f"SELECT 1 FROM {t} WHERE client_name = ?{cond.format(col=c)} LIMIT 1",
                                    [name] + extra).fetchone() for t, c in _HISTORY):
                return None
            now = int(time.time())
            key = f"{name}#{now}"
            for table, col in _HISTORY:
                conn.execute(f"UPDATE {table} SET client_name = ? WHERE client_name = ?{cond.format(col=col)}",
                             [key, name] + extra)
            conn.execute("INSERT INTO archived_clients (key, name, archived_at) VALUES (?, ?, ?) ON CONFLICT(key) DO UPDATE SET name=excluded.name, archived_at=excluded.archived_at",
                         (key, name, now))
            return key

    def purge_client(self, name: str) -> None:
        """Remove every trace of a pseudo client (OpenVPN's "UNDEF" for handshakes in progress)."""
        with self.tx() as conn:
            for table, _ in _HISTORY:
                conn.execute(f"DELETE FROM {table} WHERE client_name = ?", (name,))
            conn.execute("DELETE FROM events WHERE client_name = ?", (name,))

    # -- rejected connection attempts ----------------------------------------
    def add_rejection(self, conn: Connection, ts: int, client: str, reason: str, address: str) -> None:
        conn.execute(
            """INSERT INTO rejections (day, client_name, reason, address, count, last_ts) VALUES (?, ?, ?, ?, 1, ?)
               ON CONFLICT(day, client_name, reason, address) DO UPDATE SET
                   count = rejections.count + 1, last_ts = GREATEST(rejections.last_ts, excluded.last_ts)""",
            (ts - ts % 86400, client, reason, address, ts),
        )

    def rejections(self, since: int, client: str | None = None) -> list[dict[str, Any]]:
        where, params = "WHERE last_ts >= ?", [since]
        if client is not None:
            where += " AND client_name = ?"
            params.append(client)
        rows = self.query(
            f"""SELECT client_name, reason, address, SUM(count) AS n, MAX(last_ts) AS last_ts FROM rejections {where}
                GROUP BY client_name, reason, address ORDER BY last_ts DESC LIMIT 50""", params)
        return [{"client": r["client_name"], "reason": r["reason"], "address": r["address"],
                 "count": int(r["n"]), "last_ts": int(r["last_ts"])} for r in rows]

    # -- sessions ------------------------------------------------------------
    def close_stale_sessions(self, at: int | None = None) -> int:
        """Mark every still-open VPN session as ended (used at startup and when OpenVPN goes away)."""
        with self.tx() as conn:
            cur = conn.execute(
                "UPDATE vpn_sessions SET disconnected_at = COALESCE(?, last_seen) WHERE disconnected_at IS NULL",
                (at,),
            )
            return cur.rowcount

    @staticmethod
    def find_session(conn: Connection, client_name: str, cid: int, connected_at: int) -> dict[str, Any] | None:
        """The most recent row of a connection, matched by name, client id and start time."""
        return conn.execute(
            "SELECT id, bytes_in, bytes_out FROM vpn_sessions WHERE client_name = ? AND cid = ? AND connected_at = ? "
            "ORDER BY id DESC LIMIT 1",
            (client_name, cid, connected_at),
        ).fetchone()

    @staticmethod
    def latest_session(conn: Connection, client_name: str, address: str,
                       since: int = 0) -> dict[str, Any] | None:
        """The newest session of a client from this address (compared without the protocol prefix):
        one that is still open, or that started at or after <since>."""
        want = split_address(address)[1]
        for row in conn.execute(
                "SELECT * FROM vpn_sessions WHERE client_name = ? AND (connected_at >= ? OR disconnected_at IS NULL) "
                "ORDER BY connected_at DESC, id DESC LIMIT 20", (client_name, since)):
            if split_address(row["real_address"])[1] == want:
                return row
        return None

    @staticmethod
    def session_group(conn: Connection, client_name: str, address: str, connected_at: int) -> int | None:
        """The visit a new connection continues: the client's previous session from the same IP
        ended at most MERGE_GAP ago. None starts a new visit."""
        ip = real_ip(address)
        for row in conn.execute(
                "SELECT grp, real_address, COALESCE(disconnected_at, last_seen) AS ended FROM vpn_sessions "
                "WHERE client_name = ? ORDER BY connected_at DESC, id DESC LIMIT 20", (client_name,)):
            if real_ip(row["real_address"]) == ip:
                return row["grp"] if connected_at - row["ended"] <= MERGE_GAP else None
        return None

    def insert_session(self, conn: Connection, client_name: str, real_address: str, connected_at: int,
                       **fields: Any) -> int:
        fields = {"proto": split_address(real_address)[0], **fields, "client_name": client_name,
                  "real_address": real_address, "connected_at": connected_at,
                  "grp": self.session_group(conn, client_name, real_address, connected_at)}
        fields.setdefault("last_seen", connected_at)
        cur = conn.execute(f"INSERT INTO vpn_sessions ({', '.join(fields)}) VALUES ({', '.join('?' * len(fields))}) RETURNING id",
                           list(fields.values()))
        identity = cur.fetchone()["id"]
        if fields["grp"] is None:
            conn.execute("UPDATE vpn_sessions SET grp = id WHERE id = ?", (identity,))
        return int(identity)

    def group_sessions(self) -> int:
        """Assign a visit to every session that has none (rows written before 1.5)."""
        last: dict[tuple[str, str], tuple[int, int]] = {}     # (client, ip) -> (grp, end of its latest session)
        with self.tx() as conn:
            rows = conn.execute("SELECT id, client_name, real_address, connected_at, "
                                "COALESCE(disconnected_at, last_seen) AS ended FROM vpn_sessions "
                                "WHERE grp IS NULL ORDER BY connected_at, id").fetchall()
            for r in rows:
                key = (r["client_name"], real_ip(r["real_address"]))
                grp, ended = last.get(key, (r["id"], None))
                if ended is None or r["connected_at"] - ended > MERGE_GAP:
                    grp = r["id"]
                last[key] = (grp, max(ended or 0, r["ended"]))
                conn.execute("UPDATE vpn_sessions SET grp = ?, proto = COALESCE(proto, ?) WHERE id = ?",
                             (grp, split_address(r["real_address"])[0], r["id"]))
            return len(rows)

    def visits(self, where: str, params: list[Any], limit: int, offset: int = 0,
               active: bool = False) -> tuple[int, list[dict[str, Any]]]:
        """Sessions merged into visits, newest first: (number of visits, one page of them). A visit
        carries the address, device and end of its latest session."""
        having = " HAVING SUM(CASE WHEN disconnected_at IS NULL THEN 1 ELSE 0 END) > 0" if active else ""
        grouped = f"""SELECT grp, MIN(connected_at) AS connected_at, MAX(id) AS last_id, COUNT(*) AS connections,
                             MAX(COALESCE(disconnected_at, last_seen)) AS ended,
                             SUM(CASE WHEN disconnected_at IS NULL THEN 1 ELSE 0 END) AS open, SUM(CASE WHEN proto = 'tcp' THEN 1 ELSE 0 END) AS tcp,
                             SUM(COALESCE(disconnected_at, last_seen) - connected_at) AS online_seconds,
                             SUM(bytes_in) AS bytes_in, SUM(bytes_out) AS bytes_out
                      FROM vpn_sessions{where} GROUP BY grp{having}"""
        total = self.one(f"SELECT COUNT(*) AS n FROM ({grouped})", params)
        rows = self.query(
            f"""SELECT g.*, l.client_name, l.real_address, l.vpn_ip, l.cipher, l.proto, l.platform, l.client_ver,
                       l.end_reason
                FROM ({grouped}) g JOIN vpn_sessions l ON l.id = g.last_id
                ORDER BY g.connected_at DESC, g.grp DESC LIMIT ? OFFSET ?""", params + [limit, offset])
        out = []
        for r in rows:
            v = dict(r)
            v["disconnected_at"] = None if v.pop("open") else v.pop("ended")
            v.pop("ended", None)
            out.append(v)
        return (int(total["n"]) if total else 0), out

    def connection_stats(self, start: int, end: int) -> list[dict[str, Any]]:
        """Per client, for the sessions that started in [start, end): how many, how long, how they
        ended, how many came over TCP, and the device seen last."""
        stats: dict[str, dict[str, Any]] = {}
        for r in self.query(
                "SELECT client_name, COALESCE(disconnected_at, last_seen) - connected_at AS seconds, disconnected_at, "
                "end_reason, proto, platform, client_ver FROM vpn_sessions WHERE connected_at >= ? AND connected_at < ? "
                "ORDER BY connected_at", (start, end)):
            s = stats.setdefault(r["client_name"], {
                "name": r["client_name"], "sessions": 0, "short": 0, "tcp": 0, "left": 0, "timed_out": 0,
                "closed": 0, "other": 0, "durations": [], "platform": None, "client_ver": None})
            s["sessions"] += 1
            s["tcp"] += r["proto"] == "tcp"
            if r["disconnected_at"] is not None:
                s["durations"].append(max(r["seconds"], 0))
                s["short"] += r["seconds"] < SHORT_SESSION
                s[{"left": "left", "timed out": "timed_out", "closed": "closed"}.get(r["end_reason"], "other")] += 1
            if r["platform"]:
                s["platform"], s["client_ver"] = r["platform"], r["client_ver"]
        for s in stats.values():
            d = sorted(s.pop("durations"))
            s["median_seconds"] = d[(len(d) - 1) // 2] if d else None
        return sorted(stats.values(), key=lambda s: -s["sessions"])

    def session_stats_by_client(self) -> dict[str, dict[str, int]]:
        rows = self.query(
            """SELECT client_name, COUNT(*) AS n, COUNT(DISTINCT grp) AS visits, MAX(last_seen) AS last_seen,
                      MIN(connected_at) AS first_seen,
                      SUM(bytes_in) AS bi, SUM(bytes_out) AS bo,
                      SUM(COALESCE(disconnected_at, last_seen) - connected_at) AS online_seconds
               FROM vpn_sessions GROUP BY client_name"""
        )
        return {
            r["client_name"]: {
                "sessions": int(r["n"]),
                "visits": int(r["visits"]),
                "last_seen": int(r["last_seen"]),
                "first_seen": int(r["first_seen"]),
                "bytes_in": int(r["bi"] or 0),
                "bytes_out": int(r["bo"] or 0),
                "online_seconds": int(r["online_seconds"] or 0),
            }
            for r in rows
        }

